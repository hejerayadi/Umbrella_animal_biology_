def generer_resume_groq(texte: str, titre: str = "") -> str:
    """Génère un résumé avec Groq"""
    if not texte or len(texte) < 20:
        return "Texte trop court pour un résumé."

    if len(texte) > 4000:
        texte = texte[:4000]

    messages = [
        {
            "role": "system",
            "content": """Tu es un expert en biologie animale et génomique.
            Résume l'article en français (150-250 mots) avec :
            1. Contexte et problématique
            2. Méthodes principales
            3. Résultats clés
            4. Implications et conclusions"""
        },
        {
            "role": "user",
            "content": f"""Résume : {titre if titre else ''}\n\n{texte}"""
        }
    ]

    payload = {
        "model": GROQ_MODEL,
        "messages": messages,
        "max_tokens": 400,
        "temperature": 0.3
    }

    try:
        response = requests.post(GROQ_API_URL, headers=HEADERS, json=payload, timeout=45)

        if response.status_code == 429:
            time.sleep(5)
            return generer_resume_groq(texte, titre)

        response.raise_for_status()
        result = response.json()
        return result["choices"][0]["message"]["content"].strip()

    except Exception as e:
        print(f"   ❌ Erreur Groq: {e}")
        return texte[:300] + "..."



def generer_synthese_groq(resultats_top: List[Dict]) -> str:
    """Fusionne les résumés des meilleurs résultats en une synthèse unique via Groq"""
    if not resultats_top:
        return "Aucun résultat à synthétiser."

    blocs = []
    for r in resultats_top:
        titre = r.get("title", "")
        resume = r.get("resume", "") or r.get("abstract", "")
        blocs.append(f"### {titre}\n{resume}")

    texte_source = "\n\n".join(blocs)

    messages = [
        {
            "role": "system",
            "content": """Tu es un expert en biologie animale et génomique.
            À partir des résumés d'articles fournis, rédige UNE SEULE synthèse
            cohérente en français (200-300 mots) qui :
            1. Dégage les points communs et convergences entre les sources
            2. Met en avant les résultats/méthodes les plus significatifs
            3. Souligne les éventuelles divergences ou nuances entre sources
            4. Conclut sur l'état des connaissances du sujet"""
        },
        {
            "role": "user",
            "content": f"Voici les résumés à synthétiser :\n\n{texte_source}"
        }
    ]

    payload = {
        "model": GROQ_MODEL,
        "messages": messages,
        "max_tokens": 500,
        "temperature": 0.3
    }

    try:
        response = requests.post(GROQ_API_URL, headers=HEADERS, json=payload, timeout=45)
        if response.status_code == 429:
            time.sleep(5)
            return generer_synthese_groq(resultats_top)
        response.raise_for_status()
        result = response.json()
        content = result["choices"][0]["message"]["content"].strip()
        content = re.sub(r'<think>.*?</think>', '', content, flags=re.DOTALL).strip()
        return content
    except Exception as e:
        print(f"   ❌ Erreur Groq (synthèse): {e}")
        return "Erreur lors de la génération de la synthèse."

