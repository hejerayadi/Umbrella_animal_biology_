class UnifiedSearchWithLLM:
    """
    Recherche unifiée avec :
    1. Génération de requêtes par LLM
    2. Recherche Firecrawl
    3. Recherche académique
    4. Embeddings sémantiques
    5. Classement par pertinence
    """

    def __init__(self):
        self.query_generator = QueryGenerator()
        self.firecrawl_engine = FirecrawlSearchEngine()
        self.academic_engine = AcademicSearchEngine()
        self.semantic_engine = SemanticEmbeddingEngine()




    def search(self, user_query: str, limit: int = 5) -> Dict:
        """
        Recherche complète avec génération de requêtes par LLM
        """
        print(f"\n🔍 RECHERCHE UNIFIÉE AVEC LLM")
        print("="*70)

        # ÉTAPE 0: Vérification du cache sémantique (Qdrant)
        print("\n🗄️ ÉTAPE 0: Vérification du cache sémantique (Qdrant)")
        print("-"*50)
        query_embedding = self.semantic_engine.generate_embeddings(user_query)
        cache_hit = chercher_similaire_qdrant(query_embedding, seuil=0.6)

        if cache_hit:
            print(f"   ✅ Résultat similaire déjà en cache (score: {cache_hit.score:.3f})")
            print("   ⏭️ Web search et OpenAlex ignorés — utilisation du cache")

            payload = cache_hit.payload
            result_cache = {
                "source": payload.get("source", "Cache Qdrant"),
                "title": payload.get("title", ""),
                "abstract": payload.get("resume", ""),
                "resume": payload.get("resume", ""),
                "url": payload.get("url", ""),
                "type": "cache",
                "relevance_score": cache_hit.score,
                "query_used": user_query,
            }

            return {
                "query_data": {
                    "search_queries": [user_query],
                    "keywords": [],
                    "secondary_concepts": []
                },
                "results": [result_cache],
                "total_found": 1,
                "from_cache": True
            }

        print("   ℹ️ Aucun résultat similaire en cache — recherche complète en cours")

        # ÉTAPE 1: Génération des requêtes par LLM
        print("\n📝 ÉTAPE 1: Génération des requêtes")
        print("-"*50)
        queries_data = self.query_generator.generate_queries(user_query)

        # ÉTAPE 2: Recherche avec Firecrawl
        print("\n🔍 ÉTAPE 2: Recherche web (Firecrawl)")
        print("-"*50)
        all_results = []

        for i, query in enumerate(queries_data["search_queries"][:3], 1):
            print(f"\n📌 Requête {i}: {query}")
            results = self.firecrawl_engine.search(query, limit=2)
            for result in results:
                result["query_used"] = query
                result["query_priority"] = i
            all_results.extend(results)

        # ÉTAPE 3: Recherche académique
        print("\n📚 ÉTAPE 3: Recherche académique")
        print("-"*50)
        academic_results = self.academic_engine.search_openalex(user_query, limit=2)
        for result in academic_results:
            result["query_used"] = user_query
            result["query_priority"] = 0
        all_results.extend(academic_results)
        print(f"   ✅ {len(academic_results)} résultats académiques")

        # ÉTAPE 4: Classement sémantique
        print("\n🧠 ÉTAPE 4: Classement sémantique")
        print("-"*50)

        for result in all_results:
            text = f"{result.get('title', '')} {result.get('abstract', '')}"
            result_embedding = self.semantic_engine.generate_embeddings(text)
            score = self.semantic_engine.semantic_similarity(query_embedding, result_embedding)
            result["relevance_score"] = score

        all_results.sort(key=lambda x: x.get("relevance_score", 0), reverse=True)

        # Élimination des doublons
        seen_titles = set()
        unique_results = []
        for result in all_results:
            title = result.get("title", "").lower()
            if title not in seen_titles and title:
                seen_titles.add(title)
                unique_results.append(result)





        print("\n📊 ÉTAPE 5: Statistiques")
        print("-"*50)
