class FirecrawlSearchEngine:
    """
    Moteur de recherche utilisant l'API Firecrawl
    """

    def __init__(self):
        self.api_key = Config.FIRECRAWL_API_KEY
        self.headers = {
            "Authorization": f"Bearer {self.api_key}",
            "Content-Type": "application/json"
        }

    def search(self, query: str, limit: int = 3) -> List[Dict]:
        """
        Recherche sur le web avec Firecrawl
        """
        results = []

        print(f"\n🌐 RECHERCHE WEB (FIRECRAWL)")
        print("="*50)
        print(f"📝 Requête: {query}")

        try:
            # Appel à l'API Firecrawl
            payload = {
                "query": query,
                "limit": limit,
                "scrapeOptions": {
                    "formats": ["markdown", "html"],
                    "onlyMainContent": True
                }
            }

            response = requests.post(
                Config.FIRECRAWL_SEARCH_URL,
                headers=self.headers,
                json=payload,
                timeout=30
            )

            if response.status_code == 200:
                data = response.json()

                # Vérification du format de réponse Firecrawl
                if data.get("success") and data.get("data"):
                    for item in data["data"]:
                        # Firecrawl retourne les résultats avec markdown, title, url, etc.
                        title = item.get("title", "Titre inconnu")
                        description = item.get("description", "")
                        url = item.get("url", "")
                        markdown = item.get("markdown", "")
                        content = item.get("content", "")

                        # Prend le meilleur contenu disponible
                        abstract = description or markdown[:500] or content[:500] or ""

                        if abstract:
                            results.append({
                                "source": "Firecrawl",
                                "title": title,
                                "abstract": abstract[:500],
                                "url": url,
                                "type": "web",
                                "full_content": markdown or content,
                                "raw_data": item
                            })

                print(f"   ✅ {len(results)} résultats trouvés")

            else:
                print(f"   ⚠️ Erreur Firecrawl: {response.status_code}")
                print(f"   Réponse: {response.text[:200]}")

        except requests.exceptions.Timeout:
            print("   ⚠️ Timeout Firecrawl")
        except Exception as e:
            print(f"   ⚠️ Erreur Firecrawl: {e}")

        return results

    def scrape_url(self, url: str) -> Optional[Dict]:
        """
        Scrape une URL spécifique avec Firecrawl
        """
        try:
            payload = {
                "url": url,
                "formats": ["markdown", "html"],
                "onlyMainContent": True
            }

            response = requests.post(
                Config.FIRECRAWL_SCRAPE_URL,
                headers=self.headers,
                json=payload,
                timeout=30
            )

            if response.status_code == 200:
                data = response.json()
                if data.get("success") and data.get("data"):
                    return data["data"]

            return None

        except Exception as e:
            print(f"   ⚠️ Erreur scraping: {e}")
            return None

