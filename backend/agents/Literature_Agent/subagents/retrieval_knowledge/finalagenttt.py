def display_results(result_data: Dict):
    """Affiche tous les résultats, avec le score du meilleur résultat en en-tête"""

    query_data = result_data.get("query_data", {})
    results = result_data.get("results", [])

    if not results:
        print("\n❌ Aucun résultat trouvé")
        return

    best_score = max((r.get("relevance_score", 0) for r in results), default=0)

    print("\n" + "="*70)
    print(f"📚 RÉSULTATS DE LA RECHERCHE")
    print(f"🏆 Meilleur score de pertinence: {best_score:.2%}")
    print("="*70)

    # Affichage des requêtes générées
    print("\n📋 REQUÊTES GÉNÉRÉES PAR LLM:")
    for i, q in enumerate(query_data.get("search_queries", []), 1):
        print(f"   {i}. {q}")

    if query_data.get("keywords"):
        print(f"\n🔑 Mots-clés: {', '.join(query_data['keywords'][:5])}")

    if query_data.get("secondary_concepts"):
        print(f"📌 Concepts: {', '.join(query_data['secondary_concepts'][:3])}")

    print(f"\n📊 {len(results)} résultats les plus pertinents")
    print("="*70)


    for i, result in enumerate(results, 1):
        score = result.get("relevance_score", 0)
        stars = "⭐" * int(score * 5) if score > 0 else "⭐⭐⭐"
        marqueur = " 🏆" if score == best_score else ""

        print(f"\n{'='*60}")
        print(f"📄 RÉSULTAT {i} | Pertinence: {score:.2%} {stars}{marqueur}")
        print(f"{'='*60}")

        print(f"📌 {result.get('title', 'N/A')}")
        print(f"📚 {result.get('source', 'N/A')}")
        print(f"🔍 Requête utilisée: {result.get('query_used', 'N/A')}")

        if result.get('type') == 'academic':
            print(f"📅 {result.get('year', 'N/A')}")
            if result.get('citations', 0) > 0:
                print(f"📊 {result.get('citations', 0)} citations")
            if result.get('doi'):
                print(f"🔗 DOI: https://doi.org/{result['doi']}")
        else:
            if result.get('url'):
                url = result['url'][:80] + "..." if len(result['url']) > 80 else result['url']
                print(f"🔗 {url}")


        abstract = result.get('abstract', '')
        resume = result.get('resume')
        if not resume and abstract and len(abstract) > 50:
            resume = generer_resume_groq(abstract, result.get('title', ''))

        if resume:
            print(f"\n📝 RÉSUMÉ:")
            print("-" * 50)
            for j in range(0, len(resume), 100):
                print(f"   {resume[j:j+100]}")
            print("-" * 50)
        elif abstract:
            print(f"\n📝 EXTRAIT:")
            print("-" * 50)
            print(f"   {abstract[:300]}...")
            print("-" * 50)




def display_synthese(result_data: Dict, semantic_engine, top_n: int = 3):
    """Génère les résumés des top_n meilleurs résultats, affiche et stocke leur synthèse"""
    results = result_data.get("results", [])
    if not results:
        print("\n❌ Aucun résultat trouvé")
        return

    query_used = result_data.get("query_data", {}).get("search_queries", ["N/A"])[0]

    # Tri par score décroissant et sélection des meilleurs
    results_tries = sorted(results, key=lambda x: x.get("relevance_score", 0), reverse=True)
    top_resultats = results_tries[:top_n]

    # Génère les résumés manquants
    for r in top_resultats:
        if not r.get("resume"):
            abstract = r.get("abstract", "")
            if abstract and len(abstract) > 50:
                r["resume"] = generer_resume_groq(abstract, r.get("title", ""))

    best_score = top_resultats[0].get("relevance_score", 0)

    print("\n" + "="*70)
    print(f"📚 SYNTHÈSE DES MEILLEURS RÉSULTATS")
    print(f"🏆 Score le plus élevé: {best_score:.2%}")
    print("="*70)

    print(f"\n📌 Sources utilisées pour la synthèse ({len(top_resultats)}):")
    for r in top_resultats:
        score = r.get("relevance_score", 0)
        ref = r.get("doi") and f"https://doi.org/{r['doi']}" or r.get("url", "N/A")
        print(f"   • {r.get('title', 'N/A')} — {score:.2%}")
        print(f"     🔗 {ref}")

    print("\n📝 SYNTHÈSE:")
    print("-" * 50)
    synthese = generer_synthese_groq(top_resultats)
    for j in range(0, len(synthese), 100):
        print(f"   {synthese[j:j+100]}")
    print("-" * 50)


    stocker_synthese_qdrant(query_used, synthese, top_resultats, semantic_engine)






def stocker_synthese_qdrant(user_query: str, synthese: str, top_resultats: List[Dict], semantic_engine):
    """
    Stocke la synthèse générée dans Qdrant, avec les titres et références
    des articles/sources utilisés pour la générer.
    """
    if not synthese or synthese.startswith("Erreur") or synthese.startswith("Aucun"):
        print("⏭️ Synthèse invalide, non stockée dans Qdrant")
        return None


    sources = []
    for r in top_resultats:
        titre = r.get("title", "N/A")
        if r.get("type") == "academic" and r.get("doi"):
            reference = f"https://doi.org/{r['doi']}"
        else:
            reference = r.get("url", "N/A")

        sources.append({
            "title": titre,
            "reference": reference,
            "source_type": r.get("source", "N/A"),
            "score": round(r.get("relevance_score", 0), 3)
        })


    texte_embedding = f"{user_query} {synthese}"
    embedding = semantic_engine.generate_embeddings(texte_embedding)

    point = PointStruct(
        id=str(uuid.uuid4()),
        vector=embedding.tolist(),
        payload={
            "type": "synthese",
            "query_used": user_query,
            "synthese": synthese,
            "sources": sources,
            "nb_sources": len(sources),
            "date": datetime.now().isoformat()
        }
    )

    try:
        get_qdrant().upsert(collection_name=COLLECTION_NAME, points=[point])
        print(f"✅ Synthèse stockée dans Qdrant avec {len(sources)} sources référencées")
        return point.id
    except Exception as e:
        print(f"   ⚠️ Erreur stockage synthèse Qdrant: {e}")
        return None



