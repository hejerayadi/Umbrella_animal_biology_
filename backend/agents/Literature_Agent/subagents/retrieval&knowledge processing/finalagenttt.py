    if query_data.get("secondary_concepts"):
        print(f"📌 Concepts: {', '.join(query_data['secondary_concepts'][:3])}")

    print(f"\n📊 {len(results)} résultats les plus pertinents")
    print("="*70)


    for i, result in enumerate(results, 1):
        score = result.get("relevance_score", 0)
        stars = "⭐" * int(score * 5) if score > 0 else "⭐⭐⭐"
        marqueur = " 🏆" if score == best_score else ""

        print(f"\n{'='*60}")
        print(f"📄 RÉSULTAT {i} | Pertinence: {score:.2%} {stars}{marqueur}")
        print(f"{'='*60}")

        print(f"📌 {result.get('title', 'N/A')}")
        print(f"📚 {result.get('source', 'N/A')}")
        print(f"🔍 Requête utilisée: {result.get('query_used', 'N/A')}")

        if result.get('type') == 'academic':
            print(f"📅 {result.get('year', 'N/A')}")
            if result.get('citations', 0) > 0:
                print(f"📊 {result.get('citations', 0)} citations")
            if result.get('doi'):
                print(f"🔗 DOI: https://doi.org/{result['doi']}")
        else:
            if result.get('url'):
                url = result['url'][:80] + "..." if len(result['url']) > 80 else result['url']
                print(f"🔗 {url}")


        abstract = result.get('abstract', '')
        resume = result.get('resume')
        if not resume and abstract and len(abstract) > 50:
            resume = generer_resume_groq(abstract, result.get('title', ''))

