from qdrant_client.models import Filter, FieldCondition, MatchValue

def chercher_similaire_qdrant(query_embedding: np.ndarray, seuil: float = 0.6, type_recherche: str = "article"):
    """
    Cherche dans Qdrant un résultat déjà stocké et sémantiquement proche
    de la requête. Filtre par type ('article' ou 'synthese') pour éviter
    de mélanger les deux formats de payload.
    """
    try:
        query_filter = Filter(
            must=[
                FieldCondition(key="type", match=MatchValue(value=type_recherche))
            ]
        )

        resultats = qdrant.query_points(
            collection_name=COLLECTION_NAME,
            query=query_embedding.tolist(),
            query_filter=query_filter,
            limit=1
        ).points
    except Exception as e:
        print(f"   ⚠️ Erreur recherche Qdrant: {e}")
        return None

    if resultats and resultats[0].score >= seuil:
        return resultats[0]
    return None
