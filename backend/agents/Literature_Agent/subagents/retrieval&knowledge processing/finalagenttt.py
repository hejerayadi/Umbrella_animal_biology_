    results = result_data.get("results", [])

    if not results:
        print("\n❌ Aucun résultat trouvé")
        return

    best_score = max((r.get("relevance_score", 0) for r in results), default=0)

    print("\n" + "="*70)
    print(f"📚 RÉSULTATS DE LA RECHERCHE")
    print(f"🏆 Meilleur score de pertinence: {best_score:.2%}")
    print("="*70)

    # Affichage des requêtes générées
