class AcademicSearchEngine:
    """Moteur de recherche académique"""

    def search_openalex(self, query: str, limit: int = 3) -> List[Dict]:
        """Recherche sur OpenAlex"""
        results = []
        try:
            params = {
                "search": query,
                "filter": "publication_year:2020-2025",
                "per_page": limit,
                "sort": "cited_by_count:desc"
            }
            response = requests.get(Config.OPENALEX_URL, params=params, timeout=30)
            response.raise_for_status()
            data = response.json()

            for paper in data.get("results", []):
                abstract = self._extract_abstract(paper)
                if abstract:
                    results.append({
                        "source": "OpenAlex",
                        "title": paper.get("title", "Titre inconnu"),
                        "abstract": abstract,
                        "authors": self._extract_authors(paper),
                        "year": paper.get("publication_year", "N/A"),
                        "citations": paper.get("cited_by_count", 0),
                        "doi": paper.get("doi", "").replace("https://doi.org/", ""),
                        "url": paper.get("doi", ""),
                        "concepts": self._extract_concepts(paper),
                        "type": "academic"
                    })

        except Exception as e:
            print(f"   ⚠️ OpenAlex: {e}")

        return results

    def _extract_abstract(self, paper):
        abstract_index = paper.get("abstract_inverted_index")
        if not abstract_index:
            return ""
        words = {}
        for word, positions in abstract_index.items():
            for pos in positions:
                words[pos] = word
        return " ".join(words[i] for i in sorted(words.keys()))

    def _extract_authors(self, paper):
        authors = []
        for auth in paper.get("authorships", []):
            nom = auth.get("author", {}).get("display_name", "")
            if nom:
                authors.append(nom)
        return authors[:5]

    def _extract_concepts(self, paper):
        concepts = []
        for concept in paper.get("concepts", [])[:3]:
            concepts.append(concept.get("display_name", ""))
        return concepts



